import type {PageCode} from '../code/pageCode.js';
import {generatePageCss} from './generatePageCss.js';
import {generatePageTsx} from './generatePageTsx.js';

/** The fields of a saved page component that the generator reads (local copy: no web code on the server). */
export type PageComponentLike={
 id?:string;type?:string;label?:string;visible?:boolean;
 position?:{x?:number;y?:number;width?:number;height?:number};
 properties?:Record<string,unknown>;
};
export type SourceIssue={componentName:string;message:string};
export type GeneratedFile={path:string;content:string};
export type GeneratedPageSource={files:GeneratedFile[];issues:Array<{componentName:string;message:string}>};

const SAFE_PAGE=/^[A-Za-z0-9_.-]{1,120}$/;
const q=(value:unknown):string=>JSON.stringify(value);
/** Generated function text goes into an object literal: indent its continuation lines. */
const indent=(text:string):string=>text.replace(/\n/g,'\n  ');
const oneLine=(text:string):string=>text.replace(/\*\//g,'').replace(/[\r\n\u2028\u2029]+/g,' ');

/**
 * A saved page -> plain code files. Pure: no database, no clock, no randomness,
 * so the same input gives byte-identical files. Never throws: what it cannot
 * write becomes an issue.
 */
export function generatePageSource(input:{
 appApi:string;pageApi:string;variant:'Desktop'|'Tablet'|'Mobile'|'Custom';
 page:{canvasWidth?:number;canvasHeight?:number;layoutMode?:string;components:PageComponentLike[]};
 pageCode:PageCode;
 /** The module text pageCode.ts builds for this page. The functions below are the same text it embeds. */
 pageCodeModuleText:string;
}):GeneratedPageSource{
 const issues:SourceIssue[]=[];
 let page=String(input.pageApi??'');
 if(!SAFE_PAGE.test(page)){
  issues.push({componentName:'',message:'Page name is not file safe: '+page});
  page=page.replace(/[^A-Za-z0-9_.-]/g,'_').slice(0,120)||'page';
 }
 const pageClass=page.replace(/[^A-Za-z0-9_-]/g,'_');
 const text='GENERATED by Une publish from Page Builder. Publishing again replaces this file. Last 10 versions: versions/'+page+'/';
 const jsHeader='// '+text;
 const components=Array.isArray(input.page?.components)?input.page.components:[];
 const pageCode=input.pageCode;

 const safe=(what:string,make:()=>string,fallback:string):string=>{
  try{return make();}
  catch(error){
   issues.push({componentName:'',message:what+' not generated: '+(error instanceof Error?error.message:String(error))});
   return fallback;
  }
 };

 const tsx=safe(page+'.tsx',()=>generatePageTsx({header:jsHeader,page,pageClass,components,pageCode},issues),jsHeader+'\n');
 const css=safe(page+'.css',()=>generatePageCss({header:'/* '+text+' */',pageClass,
  canvasWidth:input.page?.canvasWidth,canvasHeight:input.page?.canvasHeight,components},issues),'/* '+text+' */\n');

 const formulas=safe(page+'.formulas.ts',()=>{
  const body=(pageCode?.formulas??[]).map(f=>'  /** '+oneLine(String(f.property))+' */\n  '+q(f.key)+': '+indent(f.js)+',\n').join('');
  return jsHeader+"\nimport {F,O} from '@une/formula-library';\n\nexport const formulas = {\n"+body+'};\n';
 },jsHeader+'\nexport const formulas = {};\n');
 const actions=safe(page+'.actions.ts',()=>{
  const body=(pageCode?.actions??[]).map(a=>'  '+q(a.key)+': '+indent(a.js)+',\n').join('');
  return jsHeader+"\nimport {F,O} from '@une/formula-library';\n\nexport const actions = {\n"+body+'};\n';
 },jsHeader+'\nexport const actions = {};\n');
 const data=safe(page+'.data.ts',()=>
  jsHeader+'\nexport const recordSets = '+JSON.stringify(pageCode?.recordSets??[],null,1)+' as const;\n',
  jsHeader+'\nexport const recordSets = [] as const;\n');

 const files:GeneratedFile[]=[
  {path:page+'.tsx',content:tsx},
  {path:page+'.css',content:css},
  {path:page+'.formulas.ts',content:formulas},
  {path:page+'.actions.ts',content:actions},
  {path:page+'.data.ts',content:data}
 ];
 const manifestPaths=[...files.map(f=>f.path),'manifest.json'];
 const manifest=JSON.stringify({app:input.appApi,page:input.pageApi,variant:input.variant,
  pageCodeVersion:pageCode?.version??0,files:manifestPaths,issues},null,1)+'\n';
 files.push({path:'manifest.json',content:manifest});
 return {files,issues};
}

